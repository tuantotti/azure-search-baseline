"""Small interfaces allow service tests without Azure or FastAPI."""

from typing import Any, Protocol

from .schemas.agentic import AgenticRetrievalRequest, KnowledgeBaseRequest, KnowledgeSourceRequest
from .schemas.search import SearchOptions


class SearchRepository(Protocol):
    async def search(
        self,
        index: str,
        options: SearchOptions,
        version: str | None = None,
        source_token: str | None = None,
    ) -> dict[str, Any]: ...
    async def raw_search(
        self,
        index: str,
        body: dict[str, Any],
        version: str | None = None,
        source_token: str | None = None,
    ) -> dict[str, Any]: ...
    async def get_index(self, index: str, version: str | None = None) -> dict[str, Any]: ...
    async def create_index(
        self, definition: dict[str, Any], version: str | None = None
    ) -> dict[str, Any]: ...
    async def index_documents(
        self, index: str, actions: list[dict[str, Any]], version: str | None = None
    ) -> dict[str, Any]: ...


class EmbeddingProvider(Protocol):
    async def embed(self, texts: list[str]) -> dict[str, Any]: ...


class AgenticRepository(Protocol):
    async def create_knowledge_source(
        self, name: str, request: "KnowledgeSourceRequest"
    ) -> dict[str, Any]: ...
    async def get_knowledge_source(self, name: str) -> dict[str, Any]: ...
    async def create_knowledge_base(
        self, name: str, request: "KnowledgeBaseRequest"
    ) -> dict[str, Any]: ...
    async def get_knowledge_base(self, name: str) -> dict[str, Any]: ...
    async def retrieve(
        self, name: str, request: "AgenticRetrievalRequest", source_token: str | None = None
    ) -> dict[str, Any]: ...


class IndexerRepository(Protocol):
    def summary_skill(self, prompt: str) -> dict[str, Any]: ...
    def billing_connection(self) -> dict[str, Any] | None: ...
    async def get_indexer(self, name: str) -> dict[str, Any]: ...
    async def get_skillset(self, name: str) -> dict[str, Any]: ...
    async def read_index(self, name: str) -> dict[str, Any]: ...
    async def create_skillset(self, definition: dict[str, Any]) -> None: ...
    async def update_index(self, definition: dict[str, Any]) -> None: ...
    async def update_indexer(self, definition: dict[str, Any]) -> None: ...
    async def indexer_operation(self, name: str, operation: str) -> dict[str, Any]: ...
